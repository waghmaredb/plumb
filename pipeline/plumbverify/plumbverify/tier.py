"""Source-tier assignment (spec C8, CL-008) and AI-generated / content-farm
scoring stub (spec C7, CL-007)."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import yaml
from bs4 import BeautifulSoup

from .models import Tier
from .upstream import host_of

DEFAULT_RULES_PATH = Path(__file__).with_name("tiers.yaml")
TIER_ORDER = [Tier.T1, Tier.T2, Tier.T3, Tier.T4, Tier.T5]


@dataclass
class TierRules:
    default: Tier = Tier.T5
    domains: dict[Tier, list[str]] = field(default_factory=dict)
    host_patterns: dict[Tier, list[re.Pattern]] = field(default_factory=dict)
    path_patterns: dict[Tier, list[str]] = field(default_factory=dict)
    content_farms: list[str] = field(default_factory=list)


def load_tier_rules(path: str | Path | None = None, overrides: Optional[dict] = None) -> TierRules:
    """Load the YAML rule table (default: bundled tiers.yaml). `overrides` is a
    dict in the same shape merged on top (lists are appended)."""
    data = yaml.safe_load(Path(path or DEFAULT_RULES_PATH).read_text()) or {}
    if overrides:
        for tier, block in (overrides.get("tiers") or {}).items():
            tgt = data.setdefault("tiers", {}).setdefault(tier, {})
            for key, vals in block.items():
                if isinstance(vals, list):
                    tgt[key] = list(tgt.get(key, [])) + list(vals)
                else:
                    tgt[key] = vals
        if "default" in overrides:
            data["default"] = overrides["default"]
        if "content_farms" in overrides:
            data["content_farms"] = list(data.get("content_farms", [])) + list(overrides["content_farms"])
    rules = TierRules(default=Tier(data.get("default", "T5")), content_farms=[d.lower() for d in data.get("content_farms", [])])
    for tier_name, block in (data.get("tiers") or {}).items():
        t = Tier(tier_name)
        rules.domains[t] = [d.lower() for d in block.get("domains", [])]
        rules.host_patterns[t] = [re.compile(p, re.I) for p in block.get("host_patterns", [])]
        rules.path_patterns[t] = [p.lower() for p in block.get("path_patterns", [])]
    return rules


def domain_matches(host: str, pattern: str) -> bool:
    host = host.lower()
    pattern = pattern.lower()
    if pattern.startswith("."):
        return host.endswith(pattern) or host == pattern[1:]
    return host == pattern or host.endswith("." + pattern)


@dataclass
class TierAssignment:
    tier: Tier
    rule: str  # which pattern fired


def assign_tier(url: str, rules: Optional[TierRules] = None) -> TierAssignment:
    rules = rules or _default_rules()
    host = host_of(url)
    path = url.split("://", 1)[-1].split("/", 1)[-1].lower() if "/" in url.split("://", 1)[-1] else ""
    path = "/" + path
    # 1. longest domain pattern wins; ties resolve to the earlier tier (more trusted)
    best: tuple[int, int, Tier, str] | None = None
    for i, t in enumerate(TIER_ORDER):
        for pat in rules.domains.get(t, []):
            if domain_matches(host, pat):
                key = (len(pat), -i)
                if best is None or key > (best[0], -best[1]):
                    best = (len(pat), i, t, f"domain:{pat}")
    if best:
        return TierAssignment(tier=best[2], rule=best[3])
    # 2. host regexes then path substrings, in tier order
    for t in TIER_ORDER:
        for rx in rules.host_patterns.get(t, []):
            if rx.search(host):
                return TierAssignment(tier=t, rule=f"host:{rx.pattern}")
    for t in TIER_ORDER:
        for sub in rules.path_patterns.get(t, []):
            if sub in path:
                return TierAssignment(tier=t, rule=f"path:{sub}")
    return TierAssignment(tier=rules.default, rule="default")


_rules_cache: Optional[TierRules] = None


def _default_rules() -> TierRules:
    global _rules_cache
    if _rules_cache is None:
        _rules_cache = load_tier_rules()
    return _rules_cache


# --------------------------------------------------------------------------
# C7 AI-generated / content-farm heuristics (STUB: rule signals only)
# --------------------------------------------------------------------------
REJECT_THRESHOLD = 0.70

_AI_DECLARATIONS = [
    "this article was generated by ai", "generated by artificial intelligence", "written by ai",
    "ai-generated content", "this content was created using ai", "generated with chatgpt",
    "as an ai language model", "written with the help of ai",
]


@dataclass
class AigenResult:
    aigen_score: float
    farm_score: float
    signals: dict[str, float]
    hard_reject: bool
    rejected: bool
    reason: Optional[str] = None


def aigen_score(url: str, html: Optional[str] = None, text: Optional[str] = None,
                rules: Optional[TierRules] = None, threshold: float = REJECT_THRESHOLD,
                tier: Optional[Tier] = None) -> AigenResult:
    """Heuristic score in [0,1] for AI-generated and content-farm signals.

    STUB. Implemented signals: self-declared AI generation (hard), known
    content-farm list (hard), absence of named author, absence of outbound
    references, ad/affiliate density, boilerplate ratio. Not implemented
    (weight 0, recorded as -1): AI-text classifier, publication-velocity
    anomaly, domain age, duplicate-content ratio. Replace with the classifier
    chosen under spec open item 2 before G1. Soft signals only reject T4/T5
    pages (or untiered ones); T1-T3 pages are rejected on hard signals only,
    to keep false rejection of T1-T3 within the 5% spec budget.
    """
    rules = rules or _default_rules()
    host = host_of(url)
    signals: dict[str, float] = {
        "ai_classifier": -1.0, "publication_velocity": -1.0, "domain_age": -1.0, "duplicate_ratio": -1.0,
    }
    text_l = (text or "").lower()
    html_l = (html or "").lower()
    hard_reject = False
    reason = None
    if any(host == f or host.endswith("." + f) for f in rules.content_farms):
        hard_reject, reason = True, "known content-farm domain"
        signals["known_farm"] = 1.0
    else:
        signals["known_farm"] = 0.0
    if any(p in text_l or p in html_l for p in _AI_DECLARATIONS):
        hard_reject, reason = True, reason or "self-declared AI generation"
        signals["self_declared_ai"] = 1.0
    else:
        signals["self_declared_ai"] = 0.0
    soup = BeautifulSoup(html or "", "html.parser") if html else None
    if soup is not None:
        author = soup.find(attrs={"name": re.compile("author", re.I)}) or soup.find(attrs={"rel": "author"}) \
            or soup.find(class_=re.compile("author|byline", re.I))
        signals["no_author"] = 0.0 if author else 1.0
        links = soup.find_all("a", href=True)
        outbound = [a for a in links if a["href"].startswith("http") and host not in a["href"]]
        signals["no_references"] = 0.0 if outbound else 1.0
        ads = len(soup.find_all(["ins", "iframe"])) + len(soup.find_all(class_=re.compile(r"\bad[s-]?\b|advert|sponsor", re.I)))
        affiliates = sum(1 for a in links if re.search(r"(amzn\.to|tag=|affiliate|ref=|utm_medium=affiliate)", a["href"], re.I))
        signals["ad_density"] = min(1.0, (ads + affiliates) / 10.0)
        full_text = soup.get_text(" ", strip=True)
        signals["boilerplate_ratio"] = 0.0 if not full_text else max(0.0, 1.0 - min(1.0, len(text or "") / max(1, len(full_text))))
    else:
        signals.update({"no_author": 0.5, "no_references": 0.5, "ad_density": 0.0, "boilerplate_ratio": 0.0})
    weights_ai = {"self_declared_ai": 1.0, "no_author": 0.25, "no_references": 0.25, "boilerplate_ratio": 0.2}
    weights_farm = {"known_farm": 1.0, "ad_density": 0.5, "no_author": 0.2, "boilerplate_ratio": 0.2}
    ai = min(1.0, sum(signals[k] * w for k, w in weights_ai.items()))
    farm = min(1.0, sum(signals[k] * w for k, w in weights_farm.items()))
    soft_allowed = tier is None or tier in (Tier.T4, Tier.T5)
    rejected = hard_reject or (soft_allowed and (ai >= threshold or farm >= threshold))
    if rejected and reason is None:
        reason = "combined score at or above threshold"
    return AigenResult(aigen_score=round(ai, 3), farm_score=round(farm, 3), signals=signals,
                       hard_reject=hard_reject, rejected=rejected, reason=reason)
