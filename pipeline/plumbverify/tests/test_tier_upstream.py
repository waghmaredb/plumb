from plumbverify.models import Source, Tier
from plumbverify.tier import aigen_score, assign_tier, load_tier_rules
from plumbverify.upstream import (
    count_independent_upstreams, independence, is_aggregator, registrable_domain,
)


# ---- C8 tier assignment ---------------------------------------------------
def test_tier_rules_t1_regulators_and_papers():
    assert assign_tier("https://www.mas.gov.sg/regulation/guidelines").tier == Tier.T1
    assert assign_tier("https://arxiv.org/html/2604.03173v1").tier == Tier.T1
    assert assign_tier("https://doi.org/10.1000/xyz").tier == Tier.T1
    assert assign_tier("https://www.sec.gov/Archives/edgar/data/1").tier == Tier.T1
    assert assign_tier("https://www.gov.uk/guidance/x").tier == Tier.T1


def test_tier_rules_t2_official_statistics_and_ir():
    assert assign_tier("https://www.singstat.gov.sg/find-data").tier == Tier.T2  # more specific than .gov.sg
    assert assign_tier("https://investor.apple.com/sec-filings").tier == Tier.T2
    assert assign_tier("https://www.acme.com/investors/annual-report-2025.pdf").tier == Tier.T2


def test_tier_rules_t3_consulting_and_press():
    assert assign_tier("https://www.mckinsey.com/capabilities/quantumblack/our-insights/x").tier == Tier.T3
    assert assign_tier("https://fortune.com/2025/10/07/deloitte-ai-australia").tier == Tier.T3
    assert assign_tier("https://www.straitstimes.com/business/x").tier == Tier.T3


def test_tier_rules_t4_vendor_and_blog_paths():
    assert assign_tier("https://aws.amazon.com/blogs/machine-learning/x").tier == Tier.T4
    assert assign_tier("https://www.someco.com/blog/why-we-win").tier == Tier.T4
    assert assign_tier("https://medium.com/@someone/post").tier == Tier.T4


def test_tier_rules_t5_aggregators_and_default():
    assert assign_tier("https://www.statista.com/statistics/123/").tier == Tier.T5
    assert assign_tier("https://en.wikipedia.org/wiki/SOC_2").tier == Tier.T5
    assert assign_tier("https://unknown-domain-xyz.net/page").tier == Tier.T5
    assert assign_tier("https://unknown-domain-xyz.net/page").rule == "default"


def test_tier_rules_overridable(tmp_path):
    rules = load_tier_rules(overrides={"default": "T4", "tiers": {"T3": {"domains": ["unknown-domain-xyz.net"]}}})
    assert assign_tier("https://unknown-domain-xyz.net/page", rules).tier == Tier.T3
    assert assign_tier("https://nobody-knows.io/", rules).tier == Tier.T4
    yaml_path = tmp_path / "t.yaml"
    yaml_path.write_text("default: T4\ntiers:\n  T1:\n    domains: [myregulator.example]\n")
    r2 = load_tier_rules(yaml_path)
    assert assign_tier("https://myregulator.example/x", r2).tier == Tier.T1
    assert assign_tier("https://other.example/x", r2).tier == Tier.T4


# ---- C7 AI-gen / farm stub -------------------------------------------------
def test_aigen_hard_signals():
    r = aigen_score("https://blog.contentfarm.example/top-10", html="<p>hi</p>", text="hi")
    assert r.rejected and r.hard_reject and r.signals["known_farm"] == 1.0
    r2 = aigen_score("https://neutral.example/post", html="<p>This article was generated by AI.</p>", text="x")
    assert r2.rejected and r2.signals["self_declared_ai"] == 1.0


def test_aigen_clean_page_not_rejected_and_scores_in_range():
    html = '<html><head><meta name="author" content="A"></head><body><p>Long text</p><a href="https://other.org/ref">ref</a></body></html>'
    r = aigen_score("https://www.mas.gov.sg/x", html=html, text="Long text", tier=Tier.T1)
    assert not r.rejected and 0.0 <= r.aigen_score <= 1.0 and 0.0 <= r.farm_score <= 1.0
    assert r.signals["ai_classifier"] == -1.0  # stubbed signal recorded as not implemented


# ---- C6 upstream independence --------------------------------------------
def test_registrable_domain_handles_cc_slds():
    assert registrable_domain("https://www.mas.gov.sg/x") == "mas.gov.sg"
    assert registrable_domain("https://news.bbc.co.uk/x") == "bbc.co.uk"
    assert registrable_domain("https://sub.a.example.com/x") == "example.com"


def test_aggregator_detection():
    assert is_aggregator("https://www.statista.com/statistics/1/")
    assert is_aggregator("https://en.wikipedia.org/wiki/X")
    assert is_aggregator("https://www.prnewswire.com/news-releases/x")
    assert not is_aggregator("https://www.reuters.com/x")
    assert is_aggregator("https://my-agg.example/x", extra_aggregators=["my-agg.example"])


def _src(url, text, sha, tier=Tier.T3, upstream=None):
    return Source(url=url, url_final=url, sha256=sha, text_extract=text, tier=tier, upstream_of=upstream or [])


def test_independent_pair_accepted():
    a = _src("https://www.reuters.com/a", "Deloitte refunds A$440,000 after fabricated references found by the department.", "aa")
    b = _src("https://www.afr.com/b", "A Senate committee heard the firm agreed to repay part of its fee for the flawed report.", "bb")
    r = independence(a, b)
    assert r.independent, r.reasons


def test_same_domain_rejected():
    a = _src("https://www.reuters.com/a", "text one about refunds", "aa")
    b = _src("https://www.reuters.com/b", "entirely different text about audits", "bb")
    assert not independence(a, b).independent


def test_near_duplicate_content_rejected():
    body = "Deloitte Australia agreed to partially refund the department after a A$440,000 report. " * 5
    a = _src("https://www.reuters.com/a", body, "aa")
    b = _src("https://www.afr.com/b", body + " (syndicated)", "bb")
    r = independence(a, b)
    assert not r.independent and any("near-duplicate" in x for x in r.reasons)


def test_two_aggregators_of_one_study_do_not_count():
    a = _src("https://www.statista.com/1", "stat page one", "aa", tier=Tier.T5)
    b = _src("https://en.wikipedia.org/wiki/X", "wiki page", "bb", tier=Tier.T5)
    assert count_independent_upstreams([a, b]).count == 0
    # traced to the same original -> still one upstream
    a.upstream_of = ["https://www.oecd.org/study-2025"]
    b.upstream_of = ["https://www.oecd.org/study-2025"]
    assert count_independent_upstreams([a, b]).count == 1
    # traced to different originals -> two
    b.upstream_of = ["https://www.imf.org/other-study"]
    assert count_independent_upstreams([a, b]).count == 2


def test_count_greedy_three_sources():
    a = _src("https://www.reuters.com/a", "alpha text about refund one", "aa")
    b = _src("https://www.reuters.com/b", "beta text completely different", "bb")  # same domain as a
    c = _src("https://www.afr.com/c", "gamma text about the senate hearing", "cc")
    uc = count_independent_upstreams([a, b, c])
    assert uc.count == 2 and uc.accepted == [a.url, c.url]
