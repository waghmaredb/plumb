class _State:
    def __init__(self):
        self.calls: list[tuple[str, str]] = []
        self.flaky_remaining = 1


def make_handler(state: _State):
    def handler(request: httpx.Request) -> httpx.Response:
        state.calls.append((request.method, str(request.url)))
        host, path = request.url.host, request.url.path
        if host == "nxdomain.example":
            raise httpx.ConnectError("[Errno -2] Name or service not known", request=request)
        if host == "www.example-press.org":
            if path == "/old-report":
                return httpx.Response(301, headers={"location": "https://www.example-press.org/report"})
            if path == "/report":
                return httpx.Response(200, headers={"content-type": "text/html; charset=utf-8"}, content=REPORT_HTML.encode())
            if path == "/flaky":
                if state.flaky_remaining > 0:
                    state.flaky_remaining -= 1
                    return httpx.Response(503)
                return httpx.Response(200, headers={"content-type": "text/html"}, content=REPORT_HTML.encode())
            if path == "/missing":
                return httpx.Response(404)
            if path == "/head-not-allowed":
                if request.method == "HEAD":
                    return httpx.Response(405)
                return httpx.Response(200, headers={"content-type": "text/html"}, content=b"<html><body><p>ok page</p></body></html>")
        if host == "docs.example-gov.sg":
            if path == "/review.pdf":
                return httpx.Response(200, headers={"content-type": "application/pdf"}, content=REPORT_PDF)
            if path == "/mislabelled":  # PDF bytes served with an HTML content-type header
                return httpx.Response(200, headers={"content-type": "text/html; charset=utf-8"}, content=REPORT_PDF)
            if path == "/scan.pdf":
                return httpx.Response(200, headers={"content-type": "application/pdf"}, content=SCANNED_PDF)
        if host == "news.example-wire.com" and path == "/senate":
            return httpx.Response(200, headers={"content-type": "text/html"}, content=SECOND_HTML.encode())
        if host == "www.statista.com":
            return httpx.Response(200, headers={"content-type": "text/html"}, content=AGG_HTML.encode())
        if host == "blog.contentfarm.example":
            return httpx.Response(200, headers={"content-type": "text/html"}, content=FARM_HTML.encode())
        if host == "mirror.example-press.org" and path == "/report-copy":
            return httpx.Response(200, headers={"content-type": "text/html"}, content=REPORT_HTML.encode())
        return httpx.Response(404)

    return handler


